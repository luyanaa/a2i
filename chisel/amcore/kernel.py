"""Kernel: manifest-driven Amaranth wrapper around a frozen golden VHDL entity.

Reads chisel/kernels/manifest.json (auto-generated by
chisel/tools/gen_manifest_kernels.py from the frozen entities) and exposes a
clean Amaranth surface:

  - `data`/`control` ports become named Signals the pipeline wires up.
  - `pervasive` ports (vdd/gnd/clkoff_b/delay_lclkr/mpw*_b/sg_1/thold_1/nclk/
    *_si/*_so/power_logic/clk_logic) are tied off for expand_type=1, thold=0 —
    i.e. plain rising-edge registers, no scan/LCB sequence.

MSB-first convention: golden A2I buses are `std_ulogic_vector(0 to N)` where
index 0 is the MSB. Amaranth Signals index [0] as LSB, so the wrapper exposes
each bus as a flat N-bit Signal and emits a `[width-1-i]` bit-swap inside the
Instance port map so golden index i maps to Signal bit (width-1-i). The
pipeline sees a normal LSB-first value; the boundary does the swap.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Optional

from amaranth import Cat, Elaboratable, Instance, Module, Signal

MANIFEST = Path(__file__).resolve().parents[1] / "kernels" / "manifest.json"

# Pervasive ports and their tie-off values for expand_type=1 / thold=0.
# '1' ties high; '0' ties low. These are the constants that make the tri
# latches behave as ordinary rising-edge registers (no scan/sg sequence).
PERVASIVE_TIE = {
    "vdd": None,            # power_logic — left unconnected (inout)
    "gnd": None,
    "nclk": None,           # clk_logic record — driven by the real clock net
    "clkoff_b": 1,          # active-low clock-off => 1 keeps clock on
    "act_dis": 0,           # activity enabled
    "delay_lclkr": 0,
    "mpw1_b": 1,
    "mpw2_b": 1,
    "sg_1": 0,              # scan gate off => functional path
    "thold_1": 0,           # thold=0 => plain rising-edge regs
}

# Pervasive *enable* pins (dc_act family) that the manifest may classify as
# 'control' but which must be tied HIGH, not driven per-instruction — they gate
# the datapath clock/activity, not operand flow.
TIE_HIGH_ENABLES = {"fpu_enable", "dc_act"}


@lru_cache(maxsize=None)
def load_manifest(path: Optional[str] = None) -> dict:
    """Load kernels/manifest.json -> {entity_name: {file, ports:[...]}}."""
    p = Path(path) if path else MANIFEST
    return json.loads(p.read_text())


def _msb_swap(width: int, sig: Signal) -> "Cat":
    """Map golden `std_ulogic_vector(0 to N)` (index0=MSB) to LSB-first Signal.

    Golden bit index i (MSB-first) corresponds to weight 2^(N-i). To expose a
    normal Amaranth value where bit j has weight 2^j, connect golden[i] to
    sig[width-1-i]. Building a Cat of the reversed bits does exactly that.
    """
    return Cat(sig[width - 1 - i] for i in range(width))


class Kernel(Elaboratable):
    """Instantiate a frozen entity as an Amaranth Instance blackbox.

    Ports:
      - Each `data`/`control` port -> attribute Signal named `p_<name>`
        (data) or `c_<name>` (control), width = manifest width, LSB-first.
      - `pervasive` ports -> tied off per PERVASIVE_TIE (vdd/gnd/nclk skipped:
        power/clk handled by the clocking layer, not per-instance).

    Usage:
        mul = Kernel("fuq_mul")
        m.d.comb += mul.c_ex1_act.eq(stage.valid & mul_en)
        m.d.comb += mul.p_f_fmt_ex1_a_frac.eq(operands.a[:53])
        m.submodules.fuq_mul = mul
        product_sum = mul.p_f_mul_ex2_sum   # carry-save sum, LSB-first
    """

    def __init__(self, entity: str, manifest: Optional[dict] = None):
        self.entity = entity
        m = manifest if manifest is not None else load_manifest()
        if entity not in m:
            raise KeyError(f"{entity} not in manifest ({MANIFEST})")
        self._spec = m[entity]
        # expose clean named signals for every non-pervasive port, prefixed by
        # role: c_<name> for control (act/flush/enable), p_<name> for data.
        self.ports = {}
        for p in self._spec["ports"]:
            if p["role"] == "pervasive" or p["name"] in TIE_HIGH_ENABLES:
                continue
            name = p["name"]
            w = p["width"]
            s = Signal(w, name=name)
            self.ports[name] = s
            prefix = "c_" if p["role"] == "control" else "p_"
            setattr(self, f"{prefix}{name}", s)

    def elaborate(self, platform):
        m = Module()
        kwargs = {}
        for p in self._spec["ports"]:
            name, d, role = p["name"], p["dir"], p["role"]
            if role == "pervasive" or name in TIE_HIGH_ENABLES:
                if name in ("vdd", "gnd", "nclk"):
                    continue            # power/clk handled at a higher level
                if name in TIE_HIGH_ENABLES:
                    kwargs[f"i_{name}"] = 1
                    continue
                tie = PERVASIVE_TIE.get(name)
                if tie is None:          # *_si/*_so scan — tie si low, leave so open
                    if d == "in":
                        kwargs[f"i_{name}"] = 0
                    # 'out' scan-outs left unconnected
                    continue
                kwargs[f"i_{name}"] = tie
                continue
            sig = self.ports[name]
            w = p["width"]
            if p["type"] == "std_ulogic_vector" and p.get("msb_first") and w > 1:
                val = _msb_swap(w, sig)
            else:
                val = sig
            if d == "in":
                kwargs[f"i_{name}"] = val
            elif d == "out":
                kwargs[f"o_{name}"] = val
            else:                        # inout — leave unconnected
                continue
        m.submodules[self.entity] = Instance(self.entity, **kwargs)
        return m
